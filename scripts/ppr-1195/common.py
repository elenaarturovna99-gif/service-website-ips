def replace_cards(doc, cards):
    h8 = find_p(doc, lambda t: t.startswith("8. Технологические карты"))
    intro = next_el(h8)
    h9 = find_p(doc, lambda t: t.startswith("9. Контроль качества"))
    els = []
    cur = next_el(intro)
    while cur is not h9:
        els.append(cur)
        cur = next_el(cur)
    # prototypes from first card
    hdr = [e for e in els if e.tag == w("p") and pstyle(e) == "Heading2"][0]
    boldp = [e for e in els if e.tag == w("p") and ptext(e).startswith("Подготовительные")][0]
    bullet = [e for e in els if is_bullet(e)][0]
    tecp = [e for e in els if e.tag == w("p") and ptext(e).startswith("Технология")][0]
    qcp = [e for e in els if e.tag == w("p") and ptext(e).startswith("Операционный")][0]
    tbls = [e for e in els if e.tag == w("tbl")]
    t_ops, t_qc = tbls[0], tbls[1]
    empty = [e for e in els if e.tag == w("p") and ptext(e) == "" and pstyle(e) is None]
    empty = empty[0] if empty else None
    protos = {k: copy.deepcopy(v) for k, v in
              dict(hdr=hdr, boldp=boldp, bullet=bullet, tecp=tecp, qcp=qcp, t_ops=t_ops, t_qc=t_qc).items()}
    pe = copy.deepcopy(empty) if empty is not None else None
    for e in els:
        delete(e)
    last = intro
    def add(el):
        nonlocal last
        last.addnext(el)
        last = el
    for i, c in enumerate(cards, 1):
        h = copy.deepcopy(protos["hdr"]); set_text(h, "8.%d. Технологическая карта: %s" % (i, c["title"])); add(h)
        add(copy.deepcopy(protos["boldp"]))
        for b in c["prep"]:
            x = copy.deepcopy(protos["bullet"]); set_text(x, b); add(x)
        add(copy.deepcopy(protos["tecp"]))
        t = copy.deepcopy(protos["t_ops"]); fill_table(t, [[str(j), a, b] for j, (a, b) in enumerate(c["ops"], 1)]); add(t)
        if pe is not None: add(copy.deepcopy(pe))
        add(copy.deepcopy(protos["qcp"]))
        t = copy.deepcopy(protos["t_qc"]); fill_table(t, [list(r) for r in c["qc"]]); add(t)
        if pe is not None: add(copy.deepcopy(pe))


def build(tpl_path, cfg, out_path):
    doc = docx.Document(tpl_path)
    left = apply_common(doc, cfg)
    doc.save(out_path)
    return left
