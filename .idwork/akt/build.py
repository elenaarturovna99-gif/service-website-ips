def fill_under(p, value):
    runs = [r for r in p.runs if r.underline]
    runs[0].text = ' ' + value + ' '
    for r in runs[1:]: r.text = ''
    runs[-1].text += '\xa0'

def set_cell(tc, tbl, text, bold=False, center=None):
    c = _Cell(tc, tbl)
    ps = c.paragraphs
    for extra in ps[1:]: extra._p.getparent().remove(extra._p)
    p = ps[0]
    for r in list(p._p.findall(qn('w:r'))): p._p.remove(r)
    lines = text.split('\n')
    for i, ln in enumerate(lines):
        r = p.add_run(ln); r.font.size = Pt(12); r.bold = bold or None
        if i < len(lines) - 1: r.add_break()
    if center is not None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT

