export const getPublishedCases = () => {
  const today = todayIso();
  return cases.filter((c) => c.date <= today).sort((a, b) => b.year.localeCompare(a.year) || b.date.localeCompare(a.date));
};

export const getCase = (slug?: string) => getPublishedCases().find((c) => c.slug === slug);

